import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const TIMESTAMPED_HEADER = /^\/\/ Generated by kea-typegen on .+ GMT\. DO NOT EDIT THIS FILE MANUALLY\.$/
const STABLE_HEADER = '// Generated by kea-typegen. DO NOT EDIT THIS FILE MANUALLY.'

async function collectLogicTypes(directory) {
    const entries = await readdir(directory, { withFileTypes: true })
    const files = []

    for (const entry of entries) {
        const path = join(directory, entry.name)
        if (entry.isDirectory()) {
            files.push(...(await collectLogicTypes(path)))
        } else if (entry.name.endsWith('LogicType.ts')) {
            files.push(path)
        }
    }

    return files
}

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const productsDirectory = join(scriptDirectory, '..', '..', 'products')
const logicTypes = await collectLogicTypes(productsDirectory)

if (logicTypes.length === 0) {
    throw new Error('No generated *LogicType.ts files found under products/')
}

for (const logicType of logicTypes) {
    const source = await readFile(logicType, 'utf8')
    const [header, ...remainingLines] = source.split('\n')

    if (header === STABLE_HEADER) {
        continue
    }
    if (!TIMESTAMPED_HEADER.test(header)) {
        throw new Error(`Unexpected kea-typegen header in ${logicType}: ${header}`)
    }

    await writeFile(logicType, [STABLE_HEADER, ...remainingLines].join('\n'))
}
